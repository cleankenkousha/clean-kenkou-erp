-- -----------------------------------------------------------------
-- [事前確認] 削除対象件数の確認 (まずは以下を実行して件数をご確認ください)
-- -----------------------------------------------------------------

-- 直近1ヶ月に作成された案件数
SELECT count(*) AS "直近1ヶ月の案件数"
FROM public.jobs
WHERE created_at >= (now() - interval '1 month');

-- 直近1ヶ月に作成された請求数
SELECT count(*) AS "直近1ヶ月の請求数"
FROM public.invoices
WHERE created_at >= (now() - interval '1 month');

-- 直近1ヶ月の回収実績数
SELECT count(*) AS "直近1ヶ月の回収実績数"
FROM public.spot_collections
WHERE created_at >= (now() - interval '1 month');


-- -----------------------------------------------------------------
-- [実行パターンA] 直近1ヶ月分のデータを削除する場合
-- ※ 外部キー制約 (ON DELETE CASCADE) により、jobs を削除すると
--    関連する spot_collections や invoices も自動削除されます。
-- -----------------------------------------------------------------

-- 案件データと関連データの削除 (過去1ヶ月分)
DELETE FROM public.jobs
WHERE created_at >= (now() - interval '1 month');

